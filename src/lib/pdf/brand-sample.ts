/**
 * @fileOverview A one-page letterhead proof.
 *
 * The Theme Studio offers this so a super admin can see the school's name, logo
 * and palette on a real PDF before publishing, not on an HTML mock that might
 * drift from what the printer receives. It goes through exactly the same kit as
 * a report card or fee statement.
 */

import {
  COLORS,
  createDocument,
  downloadPdf,
  finalize,
  keyValueGrid,
  letterhead,
  sectionTitle,
  text,
  wrap,
} from './kit';
import { getActiveBrand, monogram } from '@/lib/brand/identity';
import { resolvePalette } from '@/lib/theme/palettes';

export async function buildBrandSample(): Promise<Uint8Array> {
  const brand = getActiveBrand();
  const palette = resolvePalette(brand.paletteId);

  const ctx = await createDocument({
    title: 'Letterhead proof',
    subject: `Brand proof for ${brand.name}`,
    reference: 'BRAND-PROOF',
    issuedBy: 'Theme Studio',
  });

  letterhead(ctx, 'Letterhead proof', 'Not an issued school document');

  ctx.cursorY -= 14;
  sectionTitle(ctx, 'Identity on this document');
  keyValueGrid(ctx, [
    { label: 'School', value: brand.name },
    { label: 'Short name', value: brand.shortName },
    { label: 'Motto', value: brand.motto },
    { label: 'Crest initials', value: brand.logo ? 'Uploaded logo in use' : monogram(brand.name, brand.shortName) },
    { label: 'Address', value: brand.address },
    { label: 'Contacts', value: brand.contacts },
    { label: 'Registration', value: brand.registration },
  ]);

  ctx.cursorY -= 10;
  sectionTitle(ctx, 'Palette');
  text(ctx, `${palette.name} — ${palette.description}`, ctx.margin, ctx.cursorY, {
    size: 9,
    color: COLORS.muted,
  });
  ctx.cursorY -= 20;

  const swatches: Array<[string, typeof COLORS.primary]> = [
    ['Letterhead band', COLORS.navy],
    ['Primary', COLORS.primary],
    ['Accent', COLORS.accent],
  ];
  swatches.forEach(([label, colour], index) => {
    const x = ctx.margin + index * 168;
    ctx.page.drawRectangle({ x, y: ctx.cursorY - 34, width: 152, height: 34, color: colour });
    text(ctx, label, x, ctx.cursorY - 48, { size: 8, color: COLORS.muted });
  });
  ctx.cursorY -= 70;

  sectionTitle(ctx, 'Why print colours differ from the screen');
  const note =
    'Documents always use the light variant of the palette. A colour tuned to glow on a dark dashboard ' +
    'prints as a pale wash on white paper, so the letterhead band is deepened and body text stays near-black ' +
    'regardless of the mode the operator is viewing.';
  wrap(ctx.font, note, 9, ctx.width - ctx.margin * 2).forEach((lineText) => {
    text(ctx, lineText, ctx.margin, ctx.cursorY, { size: 9, color: COLORS.ink });
    ctx.cursorY -= 13;
  });

  return await finalize(ctx, 'Generated by the Theme Studio to verify school branding.');
}

export async function downloadBrandSample(): Promise<void> {
  const bytes = await buildBrandSample();
  const slug = getActiveBrand().shortName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  downloadPdf(bytes, `${slug || 'school'}-letterhead-proof.pdf`);
}
